import chess, numpy as np
IDX = {chess.PAWN:0, chess.KNIGHT:1, chess.BISHOP:2, chess.ROOK:3, chess.QUEEN:4, chess.KING:5}

def board_to_array(board):
    x = np.zeros(769, dtype=np.float32)
    for sq, p in board.piece_map().items():
        x[(IDX[p.piece_type] + (0 if p.color else 6)) * 64 + sq] = 1
    x[768] = 1 if board.turn else 0
    return x

