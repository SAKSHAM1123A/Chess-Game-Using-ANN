def handle_square_click(square_name):
    global board, selected_square
    if board.is_game_over():
        return

    sq_idx = chess.parse_square(square_name)
    piece = board.piece_at(sq_idx)

    if selected_square is None:
        if piece is not None and piece.color == chess.WHITE:
            selected_square = sq_idx
            output.clear(wait=True)
            display(HTML(get_interactive_board_html(board, selected_square)))
            output.eval_js(f"document.getElementById('status-msg').innerText = 'Selected {square_name}. Click destination square.'")
    else:
        from_square_name = chess.square_name(selected_square)
        uci_move = f"{from_square_name}{square_name}"
        move = chess.Move.from_uci(uci_move)
        promo_move = chess.Move.from_uci(f"{uci_move}q")

        executed_move = None
        if move in board.legal_moves:
            executed_move = move
        elif promo_move in board.legal_moves:
            executed_move = promo_move

        if executed_move:
            board.push(executed_move)
            selected_square = None

            output.clear(wait=True)
            display(HTML(get_interactive_board_html(board)))

            if not board.is_game_over():
                output.eval_js("document.getElementById('status-msg').innerText = 'AI is playing...'")
                ai_move = best_move(board, depth=3)
                if ai_move:
                    board.push(ai_move)

                output.clear(wait=True)
                display(HTML(get_interactive_board_html(board)))

            if board.is_game_over():
                output.eval_js(f"document.getElementById('status-msg').innerText = 'Game Over! Result: {board.result()}'")
        else:
            if piece is not None and piece.color == chess.WHITE:
                selected_square = sq_idx
                output.clear(wait=True)
                display(HTML(get_interactive_board_html(board, selected_square)))
                output.eval_js(f"document.getElementById('status-msg').innerText = 'Switched selection to {square_name}.'")
            else:
                selected_square = None
                output.clear(wait=True)
                display(HTML(get_interactive_board_html(board)))
                output.eval_js("document.getElementById('status-msg').innerText = 'Invalid move. Selection cleared.'")

def reset_match():
    global board, selected_square
