@torch.no_grad()
def evaluate(board):
    return model(torch.tensor(board_to_array(board)).unsqueeze(0)).item()

def negamax(board, depth, alpha, beta):
    if board.is_checkmate(): return -10
    if board.is_game_over(claim_draw=True): return 0
    if depth == 0:
        return evaluate(board) * (1 if board.turn else -1)
    best = -99
    for m in board.legal_moves:
        board.push(m)
        s = -negamax(board, depth - 1, -beta, -alpha)
        board.pop()
        best = max(best, s)
        alpha = max(alpha, s)
        if alpha >= beta: break
    return best

def best_move(board, depth=3):
    best, best_s = None, -99
    for m in board.legal_moves:
        board.push(m)
        s = -negamax(board, depth - 1, -99, 99)
        board.pop()
        if s > best_s: best, best_s = m, s
    return best

